// =============================================
// FIND PRODUCT
// =============================================

function findProduct(
    productId
) {

    for (
        const category in menuData
    ) {

        const product =
            menuData[category]
                .items
                .find(
                    item =>
                        item.id === productId
                );


        if (product) {

            return product;

        }

    }


    return null;

}


// =============================================
// ORDER NOW
// =============================================

function orderNow(
    productId
) {

    const product =
        findProduct(
            productId
        );


    if (!product) {

        return;

    }


    let cart =
        JSON.parse(
            localStorage.getItem(
                "cart"
            )
        ) || [];


    const existing =
        cart.find(
            item =>
                item.id === product.id
        );


    if (existing) {

        existing.quantity++;

    } else {

        cart.push({

            ...product,

            quantity: 1

        });

    }


    localStorage.setItem(
        "cart",
        JSON.stringify(cart)
    );


    updateCartCount();


    alert(
        `${product.name} added to cart!`
    );

}


// =============================================
// CART COUNT
// =============================================

function updateCartCount() {

    const cart =
        JSON.parse(
            localStorage.getItem(
                "cart"
            )
        ) || [];


    const count =
        cart.reduce(
            (total, item) =>
                total + item.quantity,
            0
        );


    document.getElementById(
        "cartCount"
    ).innerText = count;

}


// =============================================
// OPEN CART
// =============================================

function openCart() {

    const cart =
        JSON.parse(
            localStorage.getItem(
                "cart"
            )
        ) || [];


    if (cart.length === 0) {

        alert(
            "Your cart is empty."
        );

        return;

    }


    let message =
        "YOUR CART\n\n";


    let total = 0;


    cart.forEach(item => {

        const itemTotal =
            item.price *
            item.quantity;


        total += itemTotal;


        message +=
            `${item.name} × ${item.quantity} = ₹${itemTotal}\n`;

    });


    message +=
        `\n----------------\n`;

    message +=
        `TOTAL: ₹${total}`;


    message +=
        `\n\nClick OK to place order.`;


    const placeOrder =
        confirm(message);


    if (placeOrder) {

        placeOrderNow(
            cart,
            total
        );

    }

}


// =============================================
// PLACE ORDER
// =============================================

function placeOrderNow(
    cart,
    total
) {

    let orders =
        JSON.parse(
            localStorage.getItem(
                "orders"
            )
        ) || [];


    const order = {

        id:
            "ORD" +
            Date.now(),

        items: cart,

        total: total,

        date:
            new Date()
                .toLocaleString(),

        status:
            "Order Placed"

    };


    orders.push(
        order
    );


    localStorage.setItem(
        "orders",
        JSON.stringify(
            orders
        )
    );


    // Empty cart

    localStorage.setItem(
        "cart",
        JSON.stringify([])
    );


    updateCartCount();


    alert(
        `Order placed successfully!\n\nOrder ID: ${order.id}`
    );

}


